import { pgTable, serial, text, integer, boolean, doublePrecision, jsonb, timestamp, uniqueIndex } from "drizzle-orm/pg-core";
import { createInsertSchema } from "drizzle-zod";

export const books = pgTable("books", {
  id: serial("id").primaryKey(),
  title: text("title").notNull(),
  subtitle: text("subtitle").notNull().default(""),
  author: text("author").notNull(),
  description: text("description").notNull().default(""),
  coverImage: text("cover_image").notNull().default(""),
  year: integer("original_publication_year").notNull().default(0),
  language: text("language").notNull().default("en"),
  genre: text("genre").notNull().default("Fiction"),
  isbn: text("isbn").notNull().default(""),
  sourceType: text("source_type").notNull().default("public_domain"),
  sourceUrl: text("source_url").notNull().default(""),
  rightsStatus: text("rights_status").notNull().default("unknown"),
  rightsNotes: text("rights_notes").notNull().default(""),
  license: jsonb("license").$type<Record<string, unknown>>().notNull().default({}),
  searchCount: integer("search_count").notNull().default(0),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});
export const editions = pgTable("visual_editions", {
  id: serial("id").primaryKey(),
  bookId: integer("book_id").notNull().references(() => books.id),
  editionNumber: integer("edition_number").notNull().default(1),
  version: text("version").notNull().default("1.0"),
  status: text("status").notNull().default("requested"),
  duration: doublePrecision("total_duration").notNull().default(0),
  cost: doublePrecision("generation_cost").default(0),
  qualityScore: doublePrecision("quality_score"),
  published: boolean("published").notNull().default(false),
  sample: boolean("sample").notNull().default(false),
  analysis: jsonb("analysis").$type<Record<string, unknown>>(),
  publishedAt: timestamp("published_at", { withTimezone: true }),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, t => [uniqueIndex("edition_number_unique").on(t.bookId, t.editionNumber)]);
export const chapters = pgTable("chapters", {
  id: serial("id").primaryKey(),
  editionId: integer("visual_edition_id").notNull().references(() => editions.id),
  number: integer("chapter_number").notNull(),
  title: text("title").notNull(),
  summary: text("summary").notNull().default(""),
  duration: doublePrecision("duration").notNull().default(0),
  status: text("status").notNull().default("planning"),
  sortOrder: integer("sort_order").notNull(),
  version: text("version").notNull().default("1.0"),
}, t => [uniqueIndex("chapter_number_unique").on(t.editionId, t.number)]);
export const characters = pgTable("characters", {
  id: serial("id").primaryKey(),
  bookId: integer("book_id").notNull().references(() => books.id),
  name: text("name").notNull(),
  description: text("description").notNull(),
  age: text("age").notNull().default(""),
  appearance: jsonb("appearance").$type<Record<string, unknown>>().notNull().default({}),
  wardrobe: text("wardrobe").notNull().default(""),
  personality: text("personality").notNull().default(""),
  referenceImage: text("reference_image").notNull().default(""),
  prompt: text("character_prompt").notNull().default(""),
  consistencyNotes: text("consistency_notes").notNull().default(""),
});
export const environments = pgTable("environments", {
  id: serial("id").primaryKey(),
  bookId: integer("book_id").notNull().references(() => books.id),
  name: text("name").notNull(),
  description: text("description").notNull(),
  location: text("location").notNull().default(""),
  period: text("time_period").notNull().default(""),
  visualStyle: text("visual_style").notNull().default(""),
  referenceImage: text("reference_image").notNull().default(""),
  prompt: text("environment_prompt").notNull().default(""),
  details: jsonb("details").$type<Record<string, unknown>>().notNull().default({}),
});
export const scenes = pgTable("scenes", {
  id: serial("id").primaryKey(),
  chapterId: integer("chapter_id").notNull().references(() => chapters.id),
  number: integer("scene_number").notNull(),
  title: text("title").notNull(),
  purpose: text("purpose").notNull().default(""),
  narration: text("narration").notNull(),
  visualPrompt: text("visual_prompt").notNull().default(""),
  camera: text("camera_direction").notNull().default("Slow push"),
  characterIds: jsonb("characters_present").$type<number[]>().notNull().default([]),
  environmentId: integer("environment_id").references(() => environments.id),
  duration: doublePrecision("duration").notNull().default(30),
  objective: text("educational_goal").notNull().default(""),
  sourceNotes: text("source_notes").notNull().default(""),
  spoilerLevel: text("spoiler_level").notNull().default("chapter"),
  status: text("status").notNull().default("planning"),
  currentVersionId: integer("current_version_id"),
}, t => [uniqueIndex("scene_number_unique").on(t.chapterId, t.number)]);
export const sceneVersions = pgTable("scene_versions", {
  id: serial("id").primaryKey(),
  sceneId: integer("scene_id").notNull().references(() => scenes.id),
  number: integer("version_number").notNull(),
  narration: text("narration").notNull(),
  imageUrl: text("image_asset").notNull().default(""),
  videoUrl: text("video_asset").notNull().default(""),
  audioUrl: text("audio_asset").notNull().default(""),
  captionUrl: text("caption_asset").notNull().default(""),
  renderStatus: text("render_status").notNull().default("draft"),
  provider: text("generation_provider").notNull().default("editorial"),
  model: text("generation_model").notNull().default("sample"),
  cost: doublePrecision("generation_cost").default(0),
  qualityScore: doublePrecision("quality_score"),
  notes: text("notes").notNull().default(""),
  promptMetadata: jsonb("prompt_metadata").$type<Record<string, unknown>>().notNull().default({}),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, t => [uniqueIndex("scene_version_unique").on(t.sceneId, t.number)]);
export const assets = pgTable("assets", {
  id: serial("id").primaryKey(),
  versionId: integer("scene_version_id").notNull().references(() => sceneVersions.id),
  kind: text("kind").notNull(),
  objectPath: text("object_path").notNull(),
  metadata: jsonb("metadata").$type<Record<string, unknown>>().notNull().default({}),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});
export const insertBookSchema = createInsertSchema(books).omit({ id: true, createdAt: true, updatedAt: true });
export type BookRecord = typeof books.$inferSelect;